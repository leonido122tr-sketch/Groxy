function parseMetalSections(): KnowledgeSection[] {
  const blocks = METAL_CONTENT.split(/\n\n(?=[1-7]\. )/)
  const sectionBlocks = blocks.slice(1, 8)
  return sectionBlocks.map((block, i) => {
    const firstBreak = block.indexOf('\n\n')
    const title = firstBreak > 0 ? block.slice(0, firstBreak).trim() : block.split('\n')[0]?.trim() ?? ''
    const content = firstBreak > 0 ? block.slice(firstBreak + 2).trim() : block.trim()
    return {
      title,
      imageUrl: `/knowledge/metal/section-${i + 1}.jpg`,
      content,
    }
  })
}

